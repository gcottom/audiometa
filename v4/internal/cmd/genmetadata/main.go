// Command genmetadata generates the SDK field aliases and storage reference.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"os"
	"strings"

	"github.com/gcottom/audiometa-core/v2"
)

func main() {
	registry := flag.String("registry", "../../audiometa-core/registry.go", "Go source containing field constants")
	proof := flag.String("results", "../docs/canonical-test-results.jsonl", "Go test -json result data")
	flag.Parse()
	if err := generate(*registry, *proof); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(registry, proof string) error {
	source, err := parser.ParseFile(token.NewFileSet(), registry, nil, 0)
	if err != nil {
		return err
	}
	verified, err := results(proof)
	if err != nil {
		return err
	}
	var aliases bytes.Buffer
	fmt.Fprintln(&aliases, "// Code generated by go generate. DO NOT EDIT.")
	fmt.Fprintln(&aliases, "package audiometa")
	fmt.Fprintln(&aliases, "import \"github.com/gcottom/audiometa-core/v2\"")
	fmt.Fprintln(&aliases, "const (")
	for _, decl := range source.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok || group.Tok != token.CONST {
			continue
		}
		for _, spec := range group.Specs {
			value, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			typeName, ok := value.Type.(*ast.Ident)
			if !ok || typeName.Name != "Field" {
				continue
			}
			for _, id := range value.Names {
				fmt.Fprintf(&aliases, "%s = core.%s\n", id.Name, id.Name)
			}
		}
	}
	fmt.Fprintln(&aliases, ")")
	for _, name := range []string{"Title", "Subtitle", "Album", "Artist", "AlbumArtist", "Composer", "Publisher", "Mood", "ISRC", "Genre", "Copyright", "Encoder", "Grouping", "Lyricist", "Conductor", "Arranger", "RecordLabel", "Work", "Movement"} {
		fmt.Fprintf(&aliases, "func (m *Metadata) Get%s() string { return m.text(%s) }\n", name, name)
		fmt.Fprintf(&aliases, "func (m *Metadata) Set%s(s string) error { return m.SetField(%s, TextValue(s)) }\n", name, name)
	}
	for _, name := range []string{"BPM", "TrackNumber", "TrackTotal", "DiscNumber", "DiscTotal"} {
		fmt.Fprintf(&aliases, "func (m *Metadata) Get%s() int64 { return m.integer(%s) }\n", name, name)
		fmt.Fprintf(&aliases, "func (m *Metadata) Set%s(n int64) error { return m.SetField(%s, IntValue(n)) }\n", name, name)
	}
	formatted, err := format.Source(aliases.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile("fields_generated.go", formatted, 0644); err != nil {
		return err
	}
	var matrix bytes.Buffer
	writeMatrix(&matrix, verified)
	return os.WriteFile("../docs/compatibility.md", matrix.Bytes(), 0644)
}

func results(path string) (map[string]map[core.Field]bool, error) {
	found := make(map[string]map[core.Field]bool)
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 4096), 1024*1024)
	for scanner.Scan() {
		var e struct{ Action, Test string }
		if err := json.Unmarshal(scanner.Bytes(), &e); err != nil {
			return nil, err
		}
		parts := strings.Split(e.Test, "/")
		if len(parts) == 3 && parts[0] == "TestCanonicalID3Contract" && parts[1] == "v2.2" {
			parts[0], parts[1] = "TestCanonicalContract", "ID3v2.2"
		}
		if e.Action != "pass" || len(parts) != 3 || parts[0] != "TestCanonicalContract" {
			continue
		}
		if _, ok := core.Lookup(core.Field(parts[2])); !ok {
			continue
		}
		if found[parts[1]] == nil {
			found[parts[1]] = make(map[core.Field]bool)
		}
		found[parts[1]][core.Field(parts[2])] = true
	}
	return found, scanner.Err()
}

func writeMatrix(w io.Writer, verified map[string]map[core.Field]bool) {
	formats := []core.Format{core.MP3v1, core.MP3v22, core.MP3v23, core.MP3v24, core.MP4, core.FLAC, core.Vorbis, core.Opus}
	names := []string{"ID3v1", "ID3v2.2", "ID3v2.3", "ID3v2.4", "MP4", "FLAC", "Vorbis", "Opus"}
	fmt.Fprintln(w, "<!-- Generated by go generate from the shared registry and test receipts. -->")
	fmt.Fprintln(w, "# Canonical field storage")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "The listed key is the registry’s preferred representation. Partial entries and bounded native representations can use the lossless fallback for values outside their domain. The verification † records a passing canonical field round trip and removal for the generated test sample. It does not establish independent recognition of every native representation. See the interoperability report for the independently verified subset. Unmarked mappings are specification or implementation candidates.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Field | Type | ID3v1 | ID3v2.2 | ID3v2.3 | ID3v2.4 | MP4 | FLAC | Ogg Vorbis | Ogg Opus |")
	fmt.Fprintln(w, "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
	for _, d := range core.Fields() {
		multi := ""
		if d.Multiple {
			multi = " list"
		}
		fmt.Fprintf(w, "| `%s` | %s%s |", d.ID, d.Kind, multi)
		for i, format := range formats {
			r := d.Mapping(format)
			fmt.Fprintf(w, " %s", r.Class)
			if r.Key != "" {
				fmt.Fprintf(w, " `%s`", r.Key)
			}
			if d.Mutable && verified[names[i]][d.ID] {
				fmt.Fprint(w, " †")
			}
			fmt.Fprint(w, " |")
		}
		fmt.Fprintln(w)
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "## Field definitions")
	fmt.Fprintln(w)
	for _, d := range core.Fields() {
		fmt.Fprintf(w, "- **%s** (`%s`). %s %s", d.Name, d.ID, d.Meaning, d.Constraints)
		if d.Unit != "" {
			fmt.Fprintf(w, " Unit `%s`.", d.Unit)
		}
		if !d.Mutable {
			fmt.Fprint(w, " Read-only.")
		}
		for _, format := range formats {
			r := d.Mapping(format)
			if len(r.Aliases) > 0 {
				fmt.Fprintf(w, " %s reads aliases `%s`.", format, strings.Join(r.Aliases, "`, `"))
			}
		}
		fmt.Fprintln(w)
	}
}
